log = get_logger("03_codebook"); P_OUT = out_dir(); summ = json.load(open(LOGS / "harmonize_summary.json"))

def counts(path, cols, chunk=250_000):
    m = read_meta(path); out, order = None, []
    cols = [c for c in cols if c in m.column_names]
    if "wave" not in m.column_names or not cols: return pd.DataFrame(), []
    for off in range(0, m.number_rows, chunk):
        part, _, _ = read_dta(path, row_offset=off, row_limit=chunk, usecols=["wave"] + cols)
        c = part.groupby("wave", sort=False).count()
        out = c if out is None else out.add(c, fill_value=0); order += [k for k in part["wave"].unique().tolist() if k not in order]
    return out.reindex(order).fillna(0).astype(int), order

# ---- files
files = []
for out, info in summ["files"].items():
    if info.get("skipped"):
        files.append({"file": out, "source": info["source"], "unit": "", "rows": None, "variables": None, "waves": "", "h_variables": "", "skipped": info["skipped"]}); continue
    files.append({"file": out, "source": info["source"], "unit": info["unit"], "rows": info["rows"], "variables": info["vars"],
                  "waves": ", ".join(info["waves"]), "h_variables": ", ".join(info["h_vars"]), "skipped": ""})
files = pd.DataFrame(files)

# ---- code lists (from the written files)
seen = {}
for out, info in summ["files"].items():
    if info.get("skipped"): continue
    m = read_meta(P_OUT / out)
    for c in info["h_vars"]:
        if c in seen or c not in m.column_names: continue
        seen[c] = (m.column_names_to_labels.get(c, ""), m.variable_value_labels.get(c, {}))
codes = pd.DataFrame([{"h_variable": c, "label": lab, "code": k, "text": v} for c, (lab, vals) in seen.items()
                      for k, v in (vals.items() if vals else [("", "(no value labels: string key or numeric)")])])

# ---- counts per file and wave (long)
cnt = []
for out, info in summ["files"].items():
    if info.get("skipped") or not info["h_vars"]: continue
    hv = [c for c in info["h_vars"] if c not in ("h_hhkey", "h_pkey")]
    if not hv: continue
    tab, order = counts(P_OUT / out, hv)
    if tab.empty: continue
    for w in order:
        for c in hv: cnt.append({"file": out, "wave": w, "h_variable": c, "n_nonmissing": int(tab.loc[w, c]) if c in tab.columns else 0})
cnt = pd.DataFrame(cnt, columns=["file", "wave", "h_variable", "n_nonmissing"])

hmap = pd.read_csv(P_OUT / "harmonization_map.csv", dtype=str).fillna("")
report = LOGS / "checks_report.txt"
checks = pd.DataFrame({"checks_report": report.read_text().splitlines() if report.exists() else ["(no logs/checks_report.txt yet: run 02_checks.py)"]})

